/* eslint-env node */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const iconDirectory = resolve(root, "node_modules/bootstrap-icons/icons");
const outputFile = resolve(root, "src/icons/bootstrap-icons.generated.ts");
const checkOnly = process.argv.includes("--check");
const icons = [
  ["warning", 0, "exclamation-lg"],
  ["success", 1, "check-lg"],
  ["error", 2, "x-lg"],
  ["question", 3, "question-lg"],
  ["lock", 4, "lock-fill"],
  ["sad", 5, "emoji-frown"],
  ["smile", 6, "emoji-smile"],
];

const attributes = (tag) =>
  Object.fromEntries(
    [...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((match) => [
      match[1],
      match[2],
    ])
  );

const readIcon = ([alias, legacyValue, bootstrapName]) => {
  const source = readFileSync(
    resolve(iconDirectory, `${bootstrapName}.svg`),
    "utf8"
  );
  const svg = source.match(/<svg\b([^>]*)>/);
  if (!svg) throw new Error(`Invalid Bootstrap icon SVG: ${bootstrapName}`);
  const viewBox = attributes(svg[1]).viewBox;
  const paths = [...source.matchAll(/<path\b([^>]*)\/>/g)].map((match) => {
    const path = attributes(match[1]);
    if (!path.d)
      throw new Error(`Missing path data in Bootstrap icon: ${bootstrapName}`);
    return { d: path.d, fillRule: path["fill-rule"] };
  });
  if (!viewBox || paths.length === 0)
    throw new Error(`Incomplete Bootstrap icon SVG: ${bootstrapName}`);
  return { alias, legacyValue, bootstrapName, viewBox, paths };
};

const definitions = icons.map(readIcon);
const lines = [
  "/**",
  " * Generated by scripts/generate-bootstrap-icons.mjs from bootstrap-icons 1.13.1.",
  " * Run `npm run icons:generate` after intentionally changing the selected icons.",
  " */",
  'import type { LayerIconName } from "../core/types";',
  "",
  "export interface EmbeddedBootstrapIconPath {",
  "  readonly d: string;",
  '  readonly fillRule?: "evenodd";',
  "}",
  "",
  "export interface EmbeddedBootstrapIconDefinition {",
  "  readonly legacyValue: number;",
  "  readonly bootstrapName: string;",
  "  readonly viewBox: string;",
  "  readonly paths: readonly EmbeddedBootstrapIconPath[];",
  "}",
  "",
  "export const bootstrapIconDefinitions = {",
];

for (const definition of definitions) {
  lines.push(`  ${definition.alias}: {`);
  lines.push(`    legacyValue: ${definition.legacyValue},`);
  lines.push(`    bootstrapName: ${JSON.stringify(definition.bootstrapName)},`);
  lines.push(`    viewBox: ${JSON.stringify(definition.viewBox)},`);
  lines.push("    paths: [");
  for (const path of definition.paths) {
    lines.push("      {");
    lines.push(`        d: ${JSON.stringify(path.d)},`);
    if (path.fillRule)
      lines.push(`        fillRule: ${JSON.stringify(path.fillRule)},`);
    lines.push("      },");
  }
  lines.push("    ],");
  lines.push("  },");
}

lines.push(
  "} as const satisfies Record<LayerIconName, EmbeddedBootstrapIconDefinition>;",
  ""
);
const generated = lines.join("\n");

if (checkOnly) {
  if (
    !existsSync(outputFile) ||
    readFileSync(outputFile, "utf8") !== generated
  ) {
    throw new Error(
      "Embedded Bootstrap icon registry is stale. Run `npm run icons:generate`."
    );
  }
} else {
  writeFileSync(outputFile, generated);
}
